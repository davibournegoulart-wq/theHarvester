def search_social_tools(
    query: Optional[str] = None,
    platform: Optional[str] = None,
    category: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """Filters the OSINT tools collection."""
    results = ALL_TOOLS
    if platform and platform.lower() != 'all':
        p_lower = platform.lower()
        results = [t for t in results if p_lower in t['platform'].lower()]
    if category and category.lower() != 'all':
        c_lower = category.lower()
        results = [t for t in results if c_lower in t['category'].lower()]
    if query:
        q_lower = query.lower()
        results = [
            t for t in results
            if q_lower in t['name'].lower()
            or q_lower in t['description'].lower()
            or q_lower in t['platform'].lower()
        ]
    return results

def get_platforms() -> List[str]:
    """Returns distinct available platforms."""
    return sorted(list(set(t['platform'] for t in ALL_TOOLS)))

def get_categories() -> List[str]:
    """Returns distinct available categories."""
    return sorted(list(set(t['category'] for t in ALL_TOOLS)))
